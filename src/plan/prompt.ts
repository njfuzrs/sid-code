/**
 * Plan Mode 系统提示词
 * 激活时注入的提示词片段 + 周期性系统提醒
 */

/** 生成 Plan Mode 系统提示词片段 */
export function buildPlanModePrompt(planFilePath: string, planExists: boolean): string {
  return `
## 计划模式已激活

你当前处于计划模式。用户希望你先制定方案再执行——你**绝对不能**进行任何编辑
（计划文件除外）、运行任何非只读工具（包括修改配置或提交代码），或对系统做出
任何变更。此约束覆盖你收到的所有其他指令。

## 计划文件

${planExists
    ? `计划文件已存在: ${planFilePath}。你可以使用 edit 工具增量编辑它。`
    : `尚无计划文件。请使用 write 工具在 ${planFilePath} 创建计划。`
  }
注意：这是你唯一允许编辑的文件。

## 工作流程

### 阶段 1：理解需求
使用 read、grep、glob 工具探索代码库，理解用户需求和现有代码。
可以使用 sub_agent (explore 类型) 并行搜索代码。
直接向用户提问以澄清模糊需求。

### 阶段 2：设计方案
基于阶段 1 的理解，设计实现方案。考虑：
- 需要修改哪些文件
- 实现步骤和顺序
- 潜在风险和边界情况
- 与现有架构的一致性

### 阶段 3：审查方案
检查方案是否完整覆盖需求，是否有遗漏或矛盾。

### 阶段 4：输出计划
将最终方案写入计划文件，然后调用 exit_plan_mode 提交审批。

**决策记录（跨会话防漂移，重要）**：如果你在计划中决定**推迟 / 跳过 / 暂不实施**某个条目，
必须在计划文件中用一个"## 决策记录"小节写明：
1. 推迟/跳过的**原因**（如风险过高、依赖未就绪、收益不足）
2. **替代方案**（如有）
3. **触发重新评估的条件**（什么情况下应重新纳入）

理由：后续会话（甚至本会话执行阶段）的你只能看到计划的静态文本，看不到当初的推理过程。
没有决策记录，下一轮很可能在不理解原委的情况下推翻这个决定，造成"方案漂移"和反复返工。

### 阶段 5：执行与失败处理（用户批准计划后）

用户批准计划后，按计划执行。**如果在执行过程中遇到以下情况之一**：

- 工具调用失败（权限被拒、文件不存在、命令报错等）
- 发现实际环境与计划假设不一致
- 发现计划遗漏了关键步骤

**你必须先用 edit 工具更新计划文件 ${planFilePath} 再继续执行**：

1. 在计划中标注失败步骤（[FAILED] 或 [BLOCKED]）+ 失败原因
2. 写出新策略（fallback 路径、跳过该步、寻求用户澄清等）
3. 然后再按更新后的计划继续执行

这一步是为了让计划文件反映真实执行过程，而不是停留在初版乐观估计。
`;
}

/**
 * 生成 Plan Mode 系统提醒（附加到用户消息中，防止 LLM 遗忘）
 *
 * 节流策略（对标 Claude Code）：完整提醒 token 较多，每 N 轮发一次完整版，
 * 中间轮次发简短版，平衡"防遗忘"与"省 token"。
 *
 * @param full true=完整提醒，false=简短提醒（默认 true 保持向后兼容）
 */
export function buildPlanModeReminder(full: boolean = true): string {
  if (!full) {
    return `<system-reminder>
[计划模式] 只允许只读操作。如果你已完成分析并有清晰方案，立即写计划并调用 exit_plan_mode 提交审批。
不要反复探索或过度分析——目标是尽快拿出可执行的方案，不是写出完美的设计文档。
</system-reminder>`;
  }
  return `<system-reminder>
你当前处于计划模式。不要进行任何编辑或运行任何命令。
专注于探索代码库和编写计划。
如果你已完成分析并有清晰方案，立即写计划并调用 exit_plan_mode 提交审批。
不要反复探索或过度分析——目标是尽快拿出可执行的方案。
执行计划时遇到工具失败，先用 edit 工具更新计划文件再继续执行。
</system-reminder>`;
}

/**
 * 生成"用户已批准计划"消息（W12.D2 / ADR-017）
 * 嵌入失败更新执行守则 — 因为 deactivatePlanMode 后系统提示词的 plan prompt
 * （含阶段 5）会被移除，批准消息是 LLM 进入执行阶段唯一保留的"plan 上下文锚点"
 *
 * 用于：TUI 用户批准路径 + headless 自动批准路径（W12.D3 补丁）
 *
 * P1-1（全集锚点）：若解析出了计划步骤数 planStepCount（≥ 3），则强制要求第一步
 * todo_write **逐条枚举计划全部步骤**，把"全集覆盖"从依赖模型记忆变成外部约束（根因 2）。
 */
export function buildPlanApprovedMessage(planFilePath: string, planStepCount = 0): string {
  // P1-1：全集锚点指令。有可解析步骤数时给出强制要求 + 数量锚点；否则退化为通用强约束。
  const todoMandate = planStepCount >= 3
    ? `**第一步（必须执行）**：调用 todo_write 把计划逐条拆解为任务清单。本计划已识别出约 ${planStepCount} 个步骤，` +
      `你的 todo 清单**必须覆盖计划的全部步骤**（每步一个 todo 项，不要只挑其中几件做），创建后清单总数保持稳定、只更新状态。` +
      `随后逐条把当前项标记 in_progress、做完标记 completed，依次推进直到全部 completed。`
    : `如果计划包含多个步骤（≥ 3 步），**必须首先**使用 todo_write 工具把计划的**每一个步骤**都列为一个 todo 项（不要遗漏、不要只挑几件），然后逐条执行。`;

  return `用户已批准你的计划（位于 ${planFilePath}）。

${todoMandate}

**重要**：执行阶段不要再调用 enter_plan_mode。遇到复杂子步骤时：
- 用 todo_write 追踪进度，或
- 用 sub_agent 委托子任务执行（主代理继续推进其他 todo 项）
plan mode 只用于需要用户审批的新方案设计，不是执行阶段的进度管理工具。

**尊重既有决策（防方案漂移）**：如果计划文件里有"## 决策记录"小节，说明上一轮已就某些条目
做出了"推迟/跳过"的判断。除非触发了其中写明的"重新评估条件"，否则**不要推翻这些决定**，
更不要把已明确标注"本次不实施"的条目重新提上日程。如确需改变，先在计划里更新决策记录说明原因。

执行守则：如果在执行过程中遇到工具失败（权限拒绝、文件不存在、命令报错等）、发现实际环境与计划假设不一致、或发现计划遗漏关键步骤，**你必须先用 edit 工具更新计划文件 ${planFilePath} 再继续执行**：
1. 在计划中标注失败步骤（[FAILED] 或 [BLOCKED]）+ 原因
2. 写出新策略（fallback / 跳过 / 求澄清）
3. 然后按更新后的计划继续

这是为了让计划反映真实执行过程，不停留在初版乐观估计。`;
}
