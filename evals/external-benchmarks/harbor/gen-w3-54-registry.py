#!/usr/bin/env python3
"""把「A2 已计分的那 54 题」固化成一个 dataset，供后两臂**跑同一批题**。

## 为什么必须是 dataset，而不是 `-i <task>` 子集

`w3-run.sh:159` 只把 `$JOB` 传给下游（`bash run-model-switch.sh "$JOB"`），
**额外参数不会被转发** ⇒ 想只跑某个子集，唯一的入口是换 dataset。
而且按题分批（每批一个 `-i`）会把分母碎成 N 份（理由见 08 号 §2.1），
本仓已明确禁止。

## 为什么要固化 54 而不是继续用 66

A2（sid+sonnet）实跑的结果是 **54 题进分母**：另外 12 题在 2026-09-08 23:35
额度耗尽后返 401 `Invalid token`，`turns=0` 且**一次 API 都没发出去** ⇒
判据判为「非能力失败」并移出分母（算进去等于把额度耗尽记成 sid-code 答错）。
后两臂（A1 sid+deepseek、A3 cc+sonnet）必须跑**同一批 54 题**，
否则 `compare-paired.py` 的配对分母会碎掉 —— 它按题名取交集
（`compare-paired.py:84`：`set(base) & set(new)`），任一侧缺题就整对退出。

## 题单来源

`w3-tasks-54.txt` —— 从 `runs/w3-sid-sonnet-66/*__*/result.json` 的 `task_name`
实测导出（⛔ 不是手抄，也不是从 registry 猜的）。

用法：
    python3 gen-w3-54-registry.py --dry-run   # 只看会写什么
    python3 gen-w3-54-registry.py             # 写入 registry.local.json
"""
import hashlib
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).parent
REGISTRY_LOCAL = HERE / "registry.local.json"
TASKLIST = HERE / "w3-tasks-54.txt"
SRC_NAME, SRC_VERSION = "terminal-bench-local", "2.0"
OUT_NAME, OUT_VERSION = "terminal-bench-w3-54", "2.0"


def main() -> None:
    if not TASKLIST.exists():
        sys.exit(f"⛔ 缺题单 {TASKLIST}\n"
                 f"   它应由 A2 的产物导出：\n"
                 f"   python3 -c \"import json,glob;"
                 f"print(chr(10).join(sorted(json.load(open(p))['task_name'] "
                 f"for p in glob.glob('runs/w3-sid-sonnet-66/*__*/result.json'))))\" "
                 f"> w3-tasks-54.txt")

    want = [ln.strip() for ln in TASKLIST.read_text().splitlines() if ln.strip()]
    if not want:
        sys.exit("⛔ 题单是空的 —— 不生成（空 dataset 会让分母变成 0 而不报错）")

    registry = json.loads(REGISTRY_LOCAL.read_text())
    src = next((d for d in registry
                if d.get("name") == SRC_NAME and str(d.get("version")) == SRC_VERSION), None)
    if src is None:
        sys.exit(f"⛔ registry.local.json 里没有 {SRC_NAME}@{SRC_VERSION} —— "
                 f"先跑 python3 gen-local-registry.py")

    by_name = {t["name"]: t for t in src["tasks"]}
    # 🔴 fail-closed：题单里有任何一题在源 dataset 里找不到就停手。
    # ⛔ 不许「跳过找不到的」——那会静默产出一个更小的 dataset，
    # 而分母变小这件事在跑完之前完全看不出来。
    missing = [t for t in want if t not in by_name]
    if missing:
        sys.exit(f"⛔ 题单里有 {len(missing)} 题不在 {SRC_NAME}@{SRC_VERSION} 里：{missing}\n"
                 f"   多半是镜像被清过 ⇒ 先补镜像并重跑 gen-local-registry.py，"
                 f"⛔ 别把这些题从题单里删掉（那会让两臂题集不同）")

    keep = [by_name[t] for t in want]
    names = sorted(t["name"] for t in keep)
    fp = f"{len(names)}:{hashlib.sha256(chr(10).join(names).encode()).hexdigest()[:16]}"

    entry = {
        "name": OUT_NAME,
        "version": OUT_VERSION,
        "description": (f"Terminal-Bench 2.0, pinned to the {len(keep)} tasks that A2 "
                        f"(sid+sonnet, job w3-sid-sonnet-66) actually scored. "
                        f"Used so all three arms run the SAME task set (paired comparison). "
                        f"Generated by gen-w3-54-registry.py — do not hand-edit."),
        "tasks": keep,
        "metrics": [],
    }

    print(f"源 {SRC_NAME}@{SRC_VERSION} = {len(src['tasks'])} 题")
    print(f"题单 {TASKLIST.name}        = {len(want)} 题")
    print(f"⇒ {OUT_NAME}@{OUT_VERSION} = {len(keep)} 题")
    print(f"   题集指纹（与 w3-run.sh 的 taskset_fp 同算法）= {fp}")

    # 只替换同名同版本那一条，其余（含 sample@2.0 与 local@2.0）原样保留 ——
    # 它们是已发表结论的取数源，动它们等于让旧结论不可复算。
    out = [d for d in registry
           if not (d.get("name") == OUT_NAME and str(d.get("version")) == OUT_VERSION)]
    out.append(entry)

    if "--dry-run" in sys.argv:
        print(f"\n[dry-run] 会写入 {REGISTRY_LOCAL}：")
        print("  dataset 总数 "
              f"{len(out)}：{', '.join(f'{d['name']}@{d['version']}' for d in out)}")
        return

    REGISTRY_LOCAL.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    print(f"\n✅ 已写入 {REGISTRY_LOCAL.name}")
    print(f"   datasets: {', '.join(f'{d['name']}@{d['version']}' for d in out)}")
    print("\n后两臂跑法（⚠️ 必须带 SID_HARBOR_DATASET，否则会跑回 66 题）：")
    print(f"   SID_HARBOR_DATASET={OUT_NAME}@{OUT_VERSION} ... bash w3-run.sh <job>")


if __name__ == "__main__":
    main()
