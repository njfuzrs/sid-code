#!/usr/bin/env python3
"""把「本地镜像已就绪的那些 tb2.0 题」写成一个本地 dataset，供 harbor -d 使用。

## 为什么不直接 `-d terminal-bench@2.0 --registry-url <官方>`

那样 harbor 会按官方 89 题的清单跑，而本地只有 72 张镜像 ⇒ 缺的 17 题会在
**环境构建阶段**失败。那种失败的形态是 `reward=0` + status 看着正常 ——
和「能力不行」长得一模一样（本仓已被这类假 0 咬过多次，判据见
`verifier_health.py` 的 `agent_started` / `llm_fatal`）。
⇒ **让分母在入口处就等于真实可跑题数**，比事后靠判据把它们摘出去更稳：
   摘出去要求判据不漏，而不放进来是结构性的。

另一个理由是**离线**：官方 registry.json 有 13.6MB，本机实测拉一次 **218s**
（62KB/s，还曾被 60s 超时截断成一份「HTTP 200 但 JSON 不完整」的文件）。
评测入口不该依赖那条链路。

## 产出

在 `registry.local.json` 里**新增/更新**一个 dataset（默认
`terminal-bench-local@2.0`），原有的 `terminal-bench-sample@2.0` **原样保留** ——
它是已发表结论（n=10 那批）的取数源，动它等于让旧结论不可复算。

用法：
    python3 gen-local-registry.py            # 按本地镜像实况生成
    python3 gen-local-registry.py --dry-run  # 只看会写什么
"""
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).parent
REGISTRY_LOCAL = HERE / "registry.local.json"
REGISTRY_CACHE = pathlib.Path.home() / ".cache/sid-tb-images/registry.json"
# 🔴 判据必须等于 compose 真正会拉的那个 ref，⛔ 不是「我们当初拉过什么」。
# 2026-09-09 实测教训：本地有 72 张 `ghcr.io/laude-institute/terminal-bench/<task>:2.0`,
# 而 tb2.0 在 commit 69671fb 上的 72 份 task.toml **全部**钉
# `docker_image = "alexgshaw/<task>:20251031"`（另 10 份 sample task.toml 才是 ghcr）。
# ⇒ 按 ghcr 判「就绪」会写出一个 72 题的 dataset，然后 69/72 题在
# `docker compose up` 阶段就失败（Error failed to resolve reference ...），
# 形态是 reward=None + exception，**preflight 却报「本地已有 = 72」**。
# 那批 ghcr 镜像还自证过不是任务镜像：72 个 tag 只有 67 个不同 image ID，
# regex-log / torch-pipeline-parallelism / torch-tensor-parallelism 三题共用同一个 ID。
IMAGE_PREFIX = "ghcr.io/laude-institute/terminal-bench"   # 仅 sample@2.0 用
TASK_IMAGE_REPO = "alexgshaw"        # local@2.0（commit 69671fb）钉的仓库
TASK_IMAGE_TAG = "20251031"          # 同上的 tag
SRC_NAME, SRC_VERSION = "terminal-bench", "2.0"
OUT_NAME, OUT_VERSION = "terminal-bench-local", "2.0"


def upstream_tasks() -> list[dict]:
    if not REGISTRY_CACHE.exists():
        sys.exit(f"⛔ 缺 registry 缓存: {REGISTRY_CACHE}\n"
                 f"   取一次（约 218s，用 -m 300 别用 -m 60，否则会被截断）:\n"
                 f"   curl -s -m 300 -o {REGISTRY_CACHE} "
                 f"https://raw.githubusercontent.com/laude-institute/harbor/main/registry.json")
    try:
        doc = json.loads(REGISTRY_CACHE.read_text())
    except json.JSONDecodeError as e:
        sys.exit(f"⛔ registry 缓存不完整（{REGISTRY_CACHE.stat().st_size} bytes）: {e}\n"
                 f"   多半是上次 curl 被超时截断，删掉重取。")
    datasets = doc if isinstance(doc, list) else doc.get("datasets", doc)
    for d in datasets:
        if d.get("name") == SRC_NAME and str(d.get("version")) == SRC_VERSION:
            return list(d.get("tasks") or [])
    sys.exit(f"⛔ registry 缓存里没有 {SRC_NAME}@{SRC_VERSION}")


def local_images() -> set[str]:
    """本地已有的 tb 镜像名。docker 不可达时 fail-closed。

    ⚠️ 不许在这里 fail-open：判不出本地有什么却继续生成，会写出一个
    「0 题」或「89 题」的 dataset，两种都会让整跑的分母是错的。
    """
    p = subprocess.run(["docker", "images", "--format", "{{.Repository}}:{{.Tag}}"],
                       capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit(f"⛔ docker 不可达（rc={p.returncode}）: {p.stderr.strip()[:200]}\n"
                 f"   先跑: docker context use colima-swebench")
    got = set()
    want_prefix = f"{TASK_IMAGE_REPO}/"
    want_suffix = f":{TASK_IMAGE_TAG}"
    for line in p.stdout.splitlines():
        if line.startswith(want_prefix) and line.endswith(want_suffix):
            got.add(line[len(want_prefix):-len(want_suffix)])
    return got


def main() -> None:
    tasks, have = upstream_tasks(), local_images()
    keep = [t for t in tasks if t["name"] in have]
    missing = sorted({t["name"] for t in tasks} - have)

    print(f"上游 {SRC_NAME}@{SRC_VERSION} = {len(tasks)} 题")
    print(f"本地镜像就绪               = {len(keep)} 题  ← 这就是 W3 的真实分母")
    print(f"因缺镜像被排除             = {len(missing)} 题")
    print(f"    判据 = 本地存在 {TASK_IMAGE_REPO}/<task>:{TASK_IMAGE_TAG}"
          f"（compose 真正会拉的 ref，⛔ 不是 ghcr 那批）")
    if missing:
        print(f"    缺的: {', '.join(missing)}")
    if not keep:
        sys.exit("⛔ 一题都没有，不生成（多半是 docker context 不对）")

    registry = json.loads(REGISTRY_LOCAL.read_text()) if REGISTRY_LOCAL.exists() else []
    entry = {
        "name": OUT_NAME,
        "version": OUT_VERSION,
        "description": (f"Terminal-Bench 2.0, restricted to the {len(keep)} tasks whose "
                        f"images are present locally (of {len(tasks)} upstream). "
                        f"Generated by gen-local-registry.py — do not hand-edit."),
        "tasks": keep,
        "metrics": [],
    }
    # 只替换同名同版本那一条，其余（含 sample@2.0）原样保留
    registry = [d for d in registry
                if not (d.get("name") == OUT_NAME and str(d.get("version")) == OUT_VERSION)]
    registry.append(entry)

    if "--dry-run" in sys.argv:
        print(f"\n[dry-run] 会写入 {REGISTRY_LOCAL}：")
        names = ", ".join(f"{d['name']}@{d['version']}" for d in registry)
        print(f"  dataset 总数 {len(registry)}：{names}")
        print(f"  {OUT_NAME}@{OUT_VERSION} 含 {len(keep)} 题")
        return

    REGISTRY_LOCAL.write_text(json.dumps(registry, indent=2, ensure_ascii=False) + "\n")
    names = ", ".join(f"{d['name']}@{d['version']}" for d in registry)
    print(f"\n✅ 已写入 {REGISTRY_LOCAL.name}")
    print(f"   datasets: {names}")
    print(f"\n跑法：harbor run -d {OUT_NAME}@{OUT_VERSION} --registry-path registry.local.json")


if __name__ == "__main__":
    main()
