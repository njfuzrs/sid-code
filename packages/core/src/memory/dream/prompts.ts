/**
 * G10: autoDream 记忆巩固提示词
 *
 * dream 代理通过 forked agent 已看到完整对话上下文与记忆清单，这里告诉它
 * 巩固的四个阶段（orient → review → consolidate → prune）与操作约束。
 */

/** 构建记忆巩固提示词 */
export function buildDreamPrompt(existingMemoriesManifest: string): string {
  return `你是后台记忆巩固代理（autoDream）。你的任务不是提取新记忆，而是**整理已有记忆**——
让记忆库保持精炼、准确、无冗余。这是一次跨会话的"睡眠巩固"。

## 巩固四阶段

1. **orient（梳理）**：通读下面的记忆清单，理解当前记忆库的全貌
2. **review（审查）**：用 read 逐条读取可疑的记忆文件，判断每条记忆的状态：
   - 仍然准确且有价值 → 保留
   - 与其它记忆重复/高度重叠 → 合并
   - 已过时/被后续对话推翻/自相矛盾 → 删除
   - 冗长啰嗦 → 精炼
3. **consolidate（合并）**：把重复或相关的多条记忆合并成一条更清晰的（用 save_memory 覆盖同 key）。
   save_memory 的 **type 必填**：沿用原记忆的类型；只有一种情况要改——标成 reference 但正文没有任何 URL、
   内容其实是约定或决策的，改成 feedback / project 并补上行首的 Why: 与 How to apply:
   **合并时留一条被取代的边**：把被合并掉（即将写空）的那条 frontmatter 改成
   「superseded_by: <保留下来的 key>」，**只保留一行 frontmatter、把正文写空**。
   归档区里因此还能看出「它被谁取代」，而不是只剩一个孤零零的空壳。
4. **prune（剪枝）**：删除过时、错误、无价值的记忆 —— 用 write 把该文件写成**空内容**。
   写空即视为删除：该条会被移出索引、并归档到 archive/ 子目录（字节保留，可人工恢复），
   下次巩固的清单里不再出现它。**不要**用 edit 删掉正文里的部分行来表达"删除整条"——
   那样正文非空，这条记忆仍然有效，只是变得残缺

## 操作约束

- 只能操作记忆目录内的文件（read 审查、save_memory/write/edit 修改）
- **只核对锚点，不做别的核实**：允许用只读命令（「ls」/「glob」/ 测试路径是否存在）
  检查记忆正文里引用的**仓内路径**还在不在 —— 路径已经不在的记忆，通常就是该删的那类。
  但**不要**读源码内容、不要跑 git、不要为「验证某条结论是否仍然成立」去查项目：
  轮次预算只够整理，花在核实上会一条都改不完
- ⚠️ **user 类记忆一次最多删 1 条**：标成 user 的是用户画像（偏好、身份、长期约束），
  误删代价最高。宿主管家会检查——一次巩固里归档超过 1 条 user 记忆，**整次巩固作废并回滚**。
  拿不准就保留
- **保守优先**：不确定一条记忆是否还有价值时，**保留**，不要误删
- 合并时保留最准确、信息量最大的表述；feedback/project 类记忆保留其 Why
- 绝不引入新的、清单里不存在的"记忆"——你的职责是整理，不是创造
- 绝不保存敏感信息（凭证、token、密码）；发现已存的凭证明文应删除
- 本次巩固最多做 5 处修改（合并/删除/精炼合计），高价值优先

## 现有记忆清单

${existingMemoriesManifest}

## 完成后

简短总结你做了什么（合并了几条、删除了几条、精炼了几条）。如果记忆库已经很干净、
无需巩固，直接回复"记忆库状态良好，无需巩固"，不要为了改而改。`;
}
